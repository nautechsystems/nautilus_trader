"""
Collect documentation links from Rust sources into Markdown for link checking.

Lychee reads a `.rs` file as plain text, so it finds bare URLs but not the `[label](url)`
form that most doc comments use. Reading source paths from stdin and emitting one Markdown
list item per link gives the checker a `.md` input covering the whole doc surface.

Doc comments are the bulk of it. `*_DOCS_URL` constants and any line referencing our own
documentation site are collected too, because those carry links into user-facing messages,
where a dead link is worse than in a comment, and nothing else checks them.

Each item is labelled with its source location, so a failure reported at line N of the
generated file maps back through `sed -n 'Np' <output>`.

"""

import re
import sys
from pathlib import Path


DOC_COMMENT = re.compile(r"^\s*//[/!]")
DOCS_URL_CONST = re.compile(r"\b(?:const|static)\s+[A-Z0-9_]*DOCS_URL\b")
OWN_DOCS_SITE = re.compile(r"https://nautilustrader\.io/docs/")
URL = re.compile(r"https?://[^\s<>()\[\]\"'`\\]+")


def _write(message: str) -> None:
    sys.stdout.write(f"{message}\n")


def _links_in(path: Path) -> list[tuple[str, int, str]]:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        _write(f"{path}: {e}")
        return []

    found = []
    # A `*_DOCS_URL` value usually sits on the line after its declaration, so keep
    # collecting until the statement terminates.
    in_docs_const = False
    for number, line in enumerate(text.splitlines(), start=1):
        if not in_docs_const and DOCS_URL_CONST.search(line):
            in_docs_const = True
        if in_docs_const or DOC_COMMENT.match(line) or OWN_DOCS_SITE.search(line):
            found += [
                (str(path), number, match.group(0).rstrip(".,;:")) for match in URL.finditer(line)
            ]
        if in_docs_const and ";" in line:
            in_docs_const = False
    return found


def main() -> int:
    """
    Write the collected links to the output path given as the sole argument.
    """
    output = Path(sys.argv[1])
    paths = [Path(line.strip()) for line in sys.stdin if line.strip().endswith(".rs")]

    # Deduplicate on the URL: the checker reports each unique link once, and the first
    # location is enough to find any others with a search.
    first_seen: dict[str, tuple[str, int]] = {}
    for path in sorted(paths):
        for source, number, url in _links_in(path):
            first_seen.setdefault(url, (source, number))

    lines = [
        "# Doc comment links",
        "",
        "Generated by `scripts/extract-doc-links.py`; do not edit or commit.",
        "",
    ]
    lines += [
        f"- [{source}:{number}]({url})"
        for url, (source, number) in sorted(first_seen.items(), key=lambda item: item[1])
    ]

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    _write(f"Collected {len(first_seen)} documentation links from {len(paths)} files into {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
