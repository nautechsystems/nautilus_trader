"""
Generate source allowances that preserve workspace policy after pedantic opt-ins.
"""

import argparse
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATED_REASON = "workspace policy; generated by scripts/update-clippy-allowances.py"
GENERATED = re.compile(
    r"(?m)^[ \t]*#!\[allow\(\n"
    r"(?:[ \t]+clippy::[a-z_]+,\n)*"
    rf'[ \t]+reason = "{re.escape(GENERATED_REASON)}"\n'
    r"[ \t]*\)\]\n",
)
OPT_IN = re.compile(
    r"(?m)^(?P<indent>[ \t]*)#!\[(?:warn|deny)\([^\]]*?\bclippy::pedantic\b[^\]]*?\)\]\n",
)


def main() -> int:
    """
    Update generated attributes, or fail without writing when --check finds drift.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="report drift without writing files")
    modes.add_argument(
        "--flags",
        action="store_true",
        help="print allowances for command-line opt-ins",
    )
    args = parser.parse_args()
    with (REPO_ROOT / "Cargo.toml").open("rb") as manifest:
        lints = tomllib.load(manifest)["workspace"]["lints"]["clippy"]
    allowances = sorted(
        name
        for name, config in lints.items()
        if (config if isinstance(config, str) else config["level"]) == "allow"
    )
    if args.flags:
        print(" ".join(f"-Aclippy::{name}" for name in allowances))  # noqa: T201
        return 0
    git = shutil.which("git")
    if git is None:
        raise RuntimeError("git executable is not available")
    result = subprocess.run(  # noqa: S603
        [git, "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", "*.rs"],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
        encoding="utf-8",
    )
    changed = []
    for name in result.stdout.split("\0"):
        if not name:
            continue
        path = REPO_ROOT / name
        if not path.is_file():
            continue
        source = path.read_text(encoding="utf-8")
        updated = _render(source, allowances)
        if updated != source:
            changed.append(name)
            if not args.check:
                path.write_text(updated, encoding="utf-8", newline="\n")
    if changed:
        print("\n".join(changed))  # noqa: T201
        if args.check:
            print("Run python3 -B scripts/update-clippy-allowances.py", file=sys.stderr)  # noqa: T201
            return 1
    return 0


def _render(source: str, allowances: list[str]) -> str:
    def replace(match: re.Match[str]) -> str:
        indent = match["indent"]
        lines = ["#![allow(", *(f"    clippy::{name}," for name in allowances)]
        lines.extend([f'    reason = "{GENERATED_REASON}"', ")]"])
        return match[0] + "".join(f"{indent}{line}\n" for line in lines)

    source = GENERATED.sub("", source)
    return OPT_IN.sub(replace, source) if allowances else source


if __name__ == "__main__":
    sys.exit(main())
