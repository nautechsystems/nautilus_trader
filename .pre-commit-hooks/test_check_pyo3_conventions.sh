#!/usr/bin/env bash

set -euo pipefail

REPO_ROOT=$(git rev-parse --show-toplevel)
CHECKER="$REPO_ROOT/.pre-commit-hooks/check_pyo3_names.py"
HOOK="$REPO_ROOT/.pre-commit-hooks/check_pyo3_conventions.sh"

CASE_ROOT=$(mktemp -d)
trap 'rm -rf "$CASE_ROOT"' EXIT

write_rs() {
  local path="$1"
  shift

  mkdir -p "$(dirname "$path")"
  printf '%s\n' "$@" > "$path"
}

run_checker() {
  local case_dir="$1"

  python3 -B "$CHECKER" "$case_dir/crates" > "$case_dir/output.txt" 2>&1
}

run_hook() {
  local case_dir="$1"

  (cd "$case_dir" && bash "$HOOK") > "$case_dir/output.txt" 2>&1
}

valid_case="$CASE_ROOT/valid"
write_rs "$valid_case/crates/sample/src/lib.rs" \
  '#[pyo3::pyclass(name = "OrderBook")]' \
  'pub struct PyOrderBook;' \
  '' \
  '#[pyclass(name = "Side")]' \
  'pub enum PySide { Buy, Sell }' \
  '' \
  '#[custom_data(pyo3)]' \
  'pub struct MacroData;' \
  '' \
  '#[cfg_attr(feature = "arrow", custom_data(python))]' \
  'pub struct ConditionalMacroData;' \
  '' \
  '#[pyo3::pymethods]' \
  'impl PyOrderBook {' \
  '    #[pyo3(name = "snapshot")]' \
  '    fn snapshot_py(&self) {}' \
  '' \
  '    #[pyo3(name = "from_json_bytes")]' \
  '    fn py_from_json_bytes_py(&self) {}' \
  '' \
  '    fn encode_record_batch_py(&self) {}' \
  '}' \
  '' \
  '#[pyfunction(name = "decode")]' \
  'fn decode_py() {}' \
  '' \
  '// fn line_comment_py() {}' \
  '/* fn block_comment_py() {} /* struct PyNestedComment; */ */' \
  'const SOURCE: &str = r#"#[pyclass] struct PyRawString; fn raw_string_py() {}"#;' \
  'const TEXT: &str = "#[pyclass] struct PyString; fn string_py() {}";' \
  "const BRACE: char = '{';" \
  '' \
  'struct PyInternal;' \
  'fn internal_py() {}'
write_rs "$valid_case/crates/persistence/macros/src/custom.rs" \
  'let methods = quote! {' \
  '    fn decode_record_batch_py() {}' \
  '};'
if ! run_checker "$valid_case"; then
  echo "Expected PyO3 name checker to pass valid input"
  cat "$valid_case/output.txt"
  exit 1
fi
rg -Fq "All PyO3 public names are explicit or allowlisted" "$valid_case/output.txt"

invalid_case="$CASE_ROOT/invalid"
write_rs "$invalid_case/crates/sample/src/lib.rs" \
  '#[pyclass]' \
  'pub struct PyCache;' \
  '' \
  '#[pyclass(name = "WrongBook")]' \
  'pub struct PyOrderBook;' \
  '' \
  '#[custom_data(pyo3)]' \
  'pub struct PyMacroData;' \
  '' \
  '#[cfg_attr(feature = "arrow", custom_data(python))]' \
  'pub struct PyConditionalMacroData;' \
  '' \
  '#[pymethods]' \
  'impl PyCache {' \
  '    fn load_py(&self) {}' \
  '' \
  '    #[pyo3(name = "wrong")]' \
  '    fn save_py(&self) {}' \
  '' \
  '    #[pyfunction(name = "encode_record_batch")]' \
  '    fn encode_record_batch_py(&self) {}' \
  '}'
write_rs "$invalid_case/crates/persistence/macros/src/custom.rs" \
  'let methods = quote! {' \
  '    #[pyfunction(name = "decode_record_batch")]' \
  '    fn decode_record_batch_py() {}' \
  '};'
if run_checker "$invalid_case"; then
  echo "Expected PyO3 name checker to reject invalid input"
  cat "$invalid_case/output.txt"
  exit 1
fi

for expected in \
  'PyCache must use #[pyclass(name = "Cache")]' \
  'PyOrderBook must use #[pyclass(name = "OrderBook")]' \
  'PyMacroData generated by #[custom_data(...)] must not use the Rust-only Py prefix' \
  'PyConditionalMacroData generated by #[custom_data(...)] must not use the Rust-only Py prefix' \
  'load_py must use #[pyo3(name = "load")]' \
  'save_py must use #[pyo3(name = "save")]' \
  'decode_record_batch_py must remain the public protocol name' \
  'encode_record_batch_py must remain the public protocol name'; do
  if ! rg -Fq "$expected" "$invalid_case/output.txt"; then
    echo "Expected PyO3 convention result not found: $expected"
    cat "$invalid_case/output.txt"
    exit 1
  fi
done

module_case="$CASE_ROOT/adapter-modules"
write_rs "$module_case/crates/adapters/sample/src/config.rs" \
  '#[cfg_attr(feature = "python", pyo3::pyclass(' \
  '    module = "nautilus_trader._libnautilus.sample",' \
  '))]' \
  '#[cfg_attr(feature = "python", pyo3_stub_gen::derive::gen_stub_pyclass(' \
  '    module = "nautilus_trader.adapters.sample",' \
  '))]' \
  'pub struct Config;' \
  '#[pyo3::pyclass(module = "nautilus_trader.adapters.sample")]' \
  'pub struct LegacyConfig;' \
  '#[custom_data(pyo3, stub_module = "nautilus_trader.adapters.sample")]' \
  'pub struct Data;'
if ! run_hook "$module_case"; then
  echo "Expected runtime and public stub module paths to pass"
  cat "$module_case/output.txt"
  exit 1
fi

write_rs "$module_case/crates/adapters/sample/src/invalid.rs" \
  '#[pyo3::pyclass(module = "nautilus_trader.other.sample")]' \
  'pub struct WrongRuntime;' \
  '#[cfg_attr(feature = "python", pyo3_stub_gen::derive::gen_stub_pyclass(' \
  '    module = "nautilus_trader._libnautilus.sample",' \
  '))]' \
  'pub struct WrongStub;' \
  '#[gen_stub_pyclass_enum(module = "nautilus_trader._libnautilus.sample")]' \
  'pub enum WrongEnum { Value }' \
  '#[custom_data(pyo3, stub_module = "nautilus_trader._libnautilus.sample")]' \
  'pub struct WrongData;'
if run_hook "$module_case"; then
  echo "Expected invalid runtime and private stub module paths to fail"
  exit 1
fi
for line in 1 3 7 9; do
  if ! rg -Fq "crates/adapters/sample/src/invalid.rs:$line:" "$module_case/output.txt"; then
    echo "Expected module path violation on line $line"
    cat "$module_case/output.txt"
    exit 1
  fi
done

echo "PyO3 convention hook tests passed"
