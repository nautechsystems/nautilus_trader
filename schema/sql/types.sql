-- Bring databases created before these labels existed forward, because schema
-- initialization skips a CREATE TYPE that already exists
ALTER TYPE BAR_AGGREGATION ADD VALUE IF NOT EXISTS 'YEAR';
ALTER TYPE BAR_AGGREGATION ADD VALUE IF NOT EXISTS 'RENKO';
ALTER TYPE PRICE_TYPE ADD VALUE IF NOT EXISTS 'MARK';

